def friendly_error_message(exc: Exception) -> str:
    """Turn a technical error into a message users can understand."""
    text = str(exc)
    if "tokens per day" in text or "(TPD)" in text:
        return ("This site has reached its daily limit and is out of tokens for today. "
                "Please try again tomorrow.")
    return ("Something went wrong while running the research. "
            "Please try again in a few minutes.")
def _clean_inline(text: str) -> str:
    """Remove markdown symbols from one line and keep the words."""
    text = text.replace("\\*", "\x00").replace("\\_", "\x01")
    text = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r"\1 (\2)", text)
    text = re.sub(r"\*\*(.+?)\*\*", r"\1", text)
    text = re.sub(r"__(.+?)__", r"\1", text)
    text = re.sub(r"\*(.+?)\*", r"\1", text)
    text = re.sub(r"`([^`]*)`", r"\1", text)
    return text.replace("\x00", "*").replace("\x01", "_").strip()


def to_structured_text(markdown_text: str, topic: str, image_urls=None) -> str:
    """Convert the report's markdown into plain text with clear sections and no # or - symbols."""
    today = datetime.date.today().strftime("%d %B %Y")
    title = f"RESEARCH REPORT: {topic.upper()}" if topic else "RESEARCH REPORT"
    out = [title, "=" * len(title), f"Generated by ResearchMind on {today}", ""]

    header = None  # column names of the table being read
    for raw in markdown_text.splitlines():
        line = raw.strip()

        if not line:
            if out and out[-1] != "":
                out.append("")
            header = None
            continue

        # Horizontal rules become a blank line
        if re.fullmatch(r"[-*_]{3,}", line.replace(" ", "")):
            if out and out[-1] != "":
                out.append("")
            continue

        # Table rows: the first cell becomes a bullet, the other cells become labelled lines
        if line.startswith("|") and line.endswith("|"):
            cells = [c.strip() for c in line.strip("|").split("|")]
            if all(re.fullmatch(r":?-{2,}:?", c) for c in cells):
                continue  # separator row such as |---|---|
            if header is None:
                header = [_clean_inline(c) for c in cells]
                continue
            values = [_clean_inline(c) for c in cells]
            out.append("• " + values[0])
            for name, value in zip(header[1:], values[1:]):
                out.append(f"    {name}: {value}")
            out.append("")
            continue

        # Headings
        heading = re.match(r"^(#{1,6})\s+(.*)$", line)
        if heading:
            level = len(heading.group(1))
            text = _clean_inline(heading.group(2))
            out.append("")
            if level <= 2:
                out += [text.upper(), "=" * len(text)]
            else:
                out.append(text)
            out.append("")
            continue

        # Bullet points
        bullet = re.match(r"^[-*•+]\s+(.*)$", line)
        if bullet:
            out.append("  • " + _clean_inline(bullet.group(1)))
            continue

        # Numbered points
        numbered = re.match(r"^(\d+)[.)]\s+(.*)$", line)
        if numbered:
            out.append(f"  {numbered.group(1)}. " + _clean_inline(numbered.group(2)))
            continue

        out.append(_clean_inline(line))

    if image_urls:
        out += ["", "IMAGE SOURCES", "=" * len("IMAGE SOURCES")]
        out += [f"  {i}. {url}" for i, url in enumerate(image_urls, 1)]

    text = "\n".join(out)
    return re.sub(r"\n{3,}", "\n\n", text).strip() + "\n"


def fetch_recent_images(topic: str, max_images: int = 3) -> list:
    """Find recent photos about the topic. Returns a list of {'bytes', 'url'} dicts.
    Any failure returns an empty list, so the report still appears."""
    try:
        client = TavilyClient(api_key=os.getenv("TAVILY_API_KEY"))
    except Exception:
        return []

    allowed_types = {"image/jpeg", "image/png", "image/webp", "image/gif"}
    found = []
    # Try news from the last year first, since recent articles carry recent photos.
    for options in ({"topic": "news", "days": 365}, {"topic": "general"}):
        try:
            response = client.search(
                query=f"{topic} latest photos",
                max_results=5,
                include_images=True,
                **options,
            )
            found = response.get("images") or []
        except Exception:
            found = []
        if found:
            break

    images = []
    for item in found:
        url = item.get("url") if isinstance(item, dict) else item
        if not url:
            continue
        try:
            resp = requests.get(url, timeout=6, headers={"User-Agent": "Mozilla/5.0"})
            content_type = resp.headers.get("Content-Type", "").split(";")[0].strip()
            if resp.status_code == 200 and content_type in allowed_types and len(resp.content) > 5000:
                images.append({"bytes": resp.content, "url": url})
        except Exception:
            continue
        if len(images) >= max_images:
            break
    return images
